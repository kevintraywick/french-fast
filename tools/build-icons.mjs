// Generates public/icons/<codepoints>.svg from Microsoft Fluent Emoji (MIT)
// for every emoji in VOCABULARY, plus a few used by the UI.
// Run: npm run icons   (needs devDependency @iconify-json/fluent-emoji)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const set = require('@iconify-json/fluent-emoji/icons.json');
// Fluent ships no codepoint map; Noto uses the same Unicode-derived names.
const chars = require('@iconify-json/noto/chars.json');

const EXTRA = ['🐢', '🐇', '🐆', '✨', '🎉'];

export const emojiCode = (e) =>
  [...e].map((c) => c.codePointAt(0)).filter((cp) => cp !== 0xfe0f)
    .map((cp) => cp.toString(16)).join('-');

const src = readFileSync(join(root, 'src/main.js'), 'utf8');
const vocabBlock = src.match(/const VOCABULARY = \[[\s\S]*?\n\];/)[0];
const emojis = [...vocabBlock.matchAll(/emoji:\s*"([^"]+)"/g)].map((m) => m[1]);

const outDir = join(root, 'public/icons');
mkdirSync(outDir, { recursive: true });
const done = [], missing = [];
for (const e of new Set([...emojis, ...EXTRA])) {
  const code = emojiCode(e);
  const name = chars[code] || chars[code.split('-')[0]];
  const icon = name && (set.icons[name] || set.icons[set.aliases?.[name]?.parent]);
  if (!icon) { missing.push(e); continue; }
  const w = icon.width || set.width || 32, h = icon.height || set.height || 32;
  // Namespace gradient ids per file so several icons can share a page safely.
  const body = icon.body.replace(/fluentEmoji\w+/g, (id) => `${id}_${code}`);
  writeFileSync(join(outDir, `${code}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${body}</svg>\n`);
  done.push(code);
}
writeFileSync(join(root, 'src/icons/manifest.js'),
  `// Generated by tools/build-icons.mjs — do not edit.\nexport const ICON_CODES = new Set(${JSON.stringify(done)});\n`);
console.log(`icons: ${done.length} written, ${missing.length} missing`, missing.join(' '));
